def css_quiz_view(request):
    questions = CSS_QUESTIONS
    total_questions = len(questions)
    current_q = request.session.get('css_quiz_current_q', 0)
    user_answers = request.session.get('css_quiz_user_answers', [])
    score = None
    feedback = None

    if request.method == "POST":
        answer = request.POST.get('answer')
        if answer is not None:
            user_answers.append(answer)
            request.session['css_quiz_user_answers'] = user_answers
            current_q += 1
            request.session['css_quiz_current_q'] = current_q

        if current_q >= total_questions:
            correct = 0
            feedback = []
            for i, q in enumerate(questions):
                is_correct = user_answers[i] == q["answer"] if i < len(user_answers) else False
                feedback.append(is_correct)
                if is_correct:
                    correct += 1
            score = correct
            if request.user.is_authenticated:
                entry, created = LeaderboardEntry.objects.get_or_create(username=request.user.username)
                entry.css_score = max(entry.css_score, score)
                entry.save()
            request.session['css_quiz_current_q'] = 0
            request.session['css_quiz_user_answers'] = []
            return render(request, "css_quiz.html", {
                "questions": questions,
                "score": score,
                "feedback": feedback,
                "user_answers": user_answers,
                "finished": True,
                "total_questions": total_questions
            })

    if current_q < total_questions:
        question = questions[current_q]
        return render(request, "css_quiz.html", {
            "question": question,
            "current_q": current_q + 1,
            "total_questions": total_questions,
            "finished": False
        })

