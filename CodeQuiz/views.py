def leaderboard_view(request):
    """
    Display the leaderboard ranked by total score.
    """
    entries = LeaderboardEntry.objects.all()
    ranked_entries = sorted(entries, key=lambda e: e.total_score(), reverse=True)
    return render(request, 'leaderboard.html', {'entries': ranked_entries})


@csrf_exempt
def register_view(request):
    """
    Handle user registration via AJAX POST request.
    """
    if request.method == 'POST':
        try:
            data = json.loads(request.body)
            username = data.get('username')
            password = data.get('password')

            # Validate input
            if not username or not password:
                return JsonResponse({
                    'success': False,
                    'message': 'Username and password are required.'
                })

            # Check if user already exists
            if User.objects.filter(username=username).exists():
                return JsonResponse({
                    'success': False,
                    'message': 'Username already exists.'
                })

            # Create new user
            User.objects.create_user(username=username, password=password)
            return JsonResponse({
                'success': True,
                'message': 'Account created successfully!'
            })

        except json.JSONDecodeError:
            return JsonResponse({
                'success': False,
                'message': 'Invalid data format.'
            })

    return JsonResponse({
        'success': False,
        'message': 'Invalid request method.'
    })


@csrf_exempt
def login_view(request):
    """
    Handle user login via AJAX POST request.
    """
    if request.method == 'POST':
        try:
            data = json.loads(request.body)
            username = data.get('username')
            password = data.get('password')

            # Validate input
            if not username or not password:
                return JsonResponse({
                    'success': False,
                    'message': 'Username and password are required.'
                })

            # Authenticate user
            user = authenticate(request, username=username, password=password)
            if user is not None:
                login(request, user)
                return JsonResponse({
                    'success': True,
                    'message': f'Welcome back, {username}!'
                })
            else:
                return JsonResponse({
                    'success': False,
                    'message': 'Invalid username or password.'
                })

        except json.JSONDecodeError:
            return JsonResponse({
                'success': False,
                'message': 'Invalid data format.'
            })

    return JsonResponse({
        'success': False,
        'message': 'Invalid request method.'
    })


